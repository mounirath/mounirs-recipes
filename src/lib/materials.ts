/**
 * المواد الأولية (raw materials) catalog: what each material is, its role,
 * safety notes, and safe substitutions when a material is unavailable.
 * Keyed by lowercase material name so lookups are tolerant of minor
 * spelling/accent differences in recipe data.
 */

import { MATERIALS_FR } from "./materials-fr";

export interface RawMaterialInfo {
  key: string;
  /** Material name as shown in recipes (Arabic or Latin). */
  name: string;
  /** Latin/international name. */
  latin: string;
  /** What it does in the formula. */
  role: string;
  /** Detailed description / specs. */
  description: string;
  /** Physical/technical specs shown in the detail view. */
  specs: string[];
  /** Safety & handling notes. */
  safety: string[];
  /** Alternatives when unavailable (same functional class). */
  alternatives: string[];
  /** Which sections commonly use it. */
  usedIn: ("cleaners" | "cars")[];
  /** Tailwind chip classes for visual identity. */
  tone: {
    chip: string;
    iconBg: string;
  };
}

/** Localized view of a material for the active language. */
export interface LocalizedMaterial {
  key: string;
  name: string;
  latin: string;
  role: string;
  description: string;
  specs: string[];
  safety: string[];
  alternatives: string[];
  usedIn: ("cleaners" | "cars")[];
  tone: {
    chip: string;
    iconBg: string;
  };
}

/** Pick the localized fields of a material by language (French from MATERIALS_FR, Arabic fallback). */
export function localizeMaterial(
  m: RawMaterialInfo,
  lang: "ar" | "fr",
): LocalizedMaterial {
  const base = {
    key: m.key,
    latin: m.latin,
    usedIn: m.usedIn,
    tone: m.tone,
  };
  if (lang === "fr") {
    const fr = MATERIALS_FR[m.key];
    if (fr) {
      return {
        ...base,
        name: fr.name ?? m.name,
        role: fr.role,
        description: fr.description,
        specs: fr.specs,
        safety: fr.safety,
        alternatives: fr.alternatives,
      };
    }
  }
  return {
    ...base,
    name: m.name,
    role: m.role,
    description: m.description,
    specs: m.specs,
    safety: m.safety,
    alternatives: m.alternatives,
  };
}

